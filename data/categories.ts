export function getCategoryById(id: string): Category | undefined {
  return CATEGORIES.find((c) => c.id === id);
}

export function getRandomWord(categoryId: string): string {
  const cat = getCategoryById(categoryId);
  if (!cat || cat.words.length === 0) return "";
  return cat.words[Math.floor(Math.random() * cat.words.length)];
}

export const FREE_CATEGORY_IDS: string[] = [
  "animals",
  "food",
  "objects",
  "sports",
  "professions",
];

export function isBuiltInCategoryFreelyAvailable(id: string): boolean {
  return FREE_CATEGORY_IDS.includes(id);
}
